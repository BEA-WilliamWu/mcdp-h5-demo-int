        REFERENCES HTH_BEA.HTH_USER_PROFILE (PARTY_ID, CLOSE_ID),
      CONSTRAINT CK_HTH_API_PWD_CRED_STATUS CHECK (CREDENTIAL_STATUS IN ('ACTIVE', 'LOCKED'))
    )~';
  END IF;
  SELECT COUNT(*) INTO N FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'HTH_BEA' AND TABLE_NAME = 'HTH_API_PASSWORD_OPERATION'
     AND COLUMN_NAME = 'STORAGE_BACKEND';
  IF N = 0 THEN
    -- Existing operations were created by the original UAM-only implementation.
    -- New Java writes the selected backend explicitly, including DATABASE.
    EXECUTE IMMEDIATE 'ALTER TABLE HTH_BEA.HTH_API_PASSWORD_OPERATION ADD
      STORAGE_BACKEND VARCHAR2(8 BYTE) DEFAULT ''UAM'' NOT NULL';
  END IF;
  -- Preserve the historical backend on old rows; default new rows to DATABASE.
  EXECUTE IMMEDIATE 'ALTER TABLE HTH_BEA.HTH_API_PASSWORD_OPERATION MODIFY
    STORAGE_BACKEND DEFAULT ''DATABASE''';
  SELECT COUNT(*) INTO N FROM ALL_CONSTRAINTS
   WHERE OWNER = 'HTH_BEA' AND CONSTRAINT_NAME = 'CK_HTH_API_PWD_OP_BACKEND';
  IF N = 0 THEN
    EXECUTE IMMEDIATE q'~ALTER TABLE HTH_BEA.HTH_API_PASSWORD_OPERATION ADD CONSTRAINT
      CK_HTH_API_PWD_OP_BACKEND CHECK (STORAGE_BACKEND IN ('DATABASE','UAM'))~';
  END IF;
  EXECUTE IMMEDIATE q'~COMMENT ON COLUMN HTH_BEA.HTH_API_PASSWORD_CREDENTIAL.PASSWORD_HASH IS
    'pbkdf2-sha256-v1$600000$Base64(16-byte salt)$Base64(32-byte hash); never plaintext or Code ciphertext.'~';
END;

