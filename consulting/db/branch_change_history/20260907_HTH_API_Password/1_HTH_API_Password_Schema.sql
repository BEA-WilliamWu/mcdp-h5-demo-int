  'Client-generated UUID; repeated successful requests return the original result.'!';
EXECUTE IMMEDIATE q'!COMMENT ON COLUMN HTH_BEA.HTH_API_PASSWORD_OPERATION.STATUS IS
  'UNKNOWN prevents an unsafe password rotation retry after an indeterminate credential operation result.'!';

DECLARE
  N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM ALL_TABLES
   WHERE OWNER = 'HTH_BEA' AND TABLE_NAME = 'HTH_API_PASSWORD_OPERATION';
  IF N <> 1 THEN
    RAISE_APPLICATION_ERROR(-20020, 'Deploy the API Password operation schema first.');
  END IF;

  SELECT COUNT(*) INTO N FROM ALL_TABLES
   WHERE OWNER = 'HTH_BEA' AND TABLE_NAME = 'HTH_API_PASSWORD_CREDENTIAL';
  IF N = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE HTH_BEA.HTH_API_PASSWORD_CREDENTIAL (
      PARTY_ID VARCHAR2(64 BYTE) NOT NULL,
      USER_ID VARCHAR2(255 BYTE) NOT NULL,
      PASSWORD_HASH VARCHAR2(255 BYTE) NOT NULL,
      CREDENTIAL_STATUS VARCHAR2(16 BYTE) DEFAULT 'ACTIVE' NOT NULL,
      CREDENTIAL_VERSION NUMBER(10) DEFAULT 1 NOT NULL,
      LAST_REQUEST_ID VARCHAR2(36 BYTE) NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
