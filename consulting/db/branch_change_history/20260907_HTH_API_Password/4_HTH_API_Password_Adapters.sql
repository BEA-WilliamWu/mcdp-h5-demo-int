 'N', 'HTH API password credential persistence', 'HTH API password credential repository',
 'ofssuser', SYSDATE, 'ofssuser', SYSDATE, NULL, 1, 'N', NULL);
DELETE FROM DIGX_FW_CONFIG_ALL_O
 WHERE PREFERENCE_NAME = 'RepositoryAdapterFactories' AND DETERMINANT_VALUE = 'OBDX_BU' AND PROP_ID = 'HTH_API_PASSWORD_CREDENTIAL_LOCAL_REPOSITORY_ADAPTER';
INSERT INTO DIGX_FW_CONFIG_ALL_O
 (PROP_ID, PREFERENCE_NAME, PROP_VALUE, DETERMINANT_VALUE, CREATED_BY,
  CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATED_DATE)
VALUES ('HTH_API_PASSWORD_CREDENTIAL_LOCAL_REPOSITORY_ADAPTER', 'RepositoryAdapterFactories',
 'com.ofss.digx.cz.bea.domain.hosttohost.entity.repository.adapter.LocalHthApiPasswordCredentialRepositoryAdapter',
 'OBDX_BU', 'ofssuser', SYSDATE, 'ofssuser', SYSDATE);

DELETE FROM DIGX_FW_CONFIG_ALL_B
 WHERE CATEGORY_ID = 'repositoryadapterconfig' AND PROP_ID = 'HTH_API_PASSWORD_STATE_LOCAL_REPOSITORY_ADAPTER';
INSERT INTO DIGX_FW_CONFIG_ALL_B
 (PROP_ID, CATEGORY_ID, PROP_VALUE, FACTORY_SHIPPED_FLAG, PROP_COMMENTS,
  SUMMARY_TEXT, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATED_DATE,
  OBJECT_STATUS, OBJECT_VERSION_NUMBER, EDITABLE, CATEGORY_DESCRIPTION)
VALUES ('HTH_API_PASSWORD_STATE_LOCAL_REPOSITORY_ADAPTER', 'repositoryadapterconfig',
 'com.ofss.digx.cz.bea.domain.hosttohost.entity.repository.adapter.LocalHthApiPasswordStateRepositoryAdapter',
 'N', 'HTH API password state persistence', 'HTH API password state repository',
 'ofssuser', SYSDATE, 'ofssuser', SYSDATE, NULL, 1, 'N', NULL);
DELETE FROM DIGX_FW_CONFIG_ALL_O
 WHERE PREFERENCE_NAME = 'RepositoryAdapterFactories' AND DETERMINANT_VALUE = 'OBDX_BU' AND PROP_ID = 'HTH_API_PASSWORD_STATE_LOCAL_REPOSITORY_ADAPTER';
INSERT INTO DIGX_FW_CONFIG_ALL_O
 (PROP_ID, PREFERENCE_NAME, PROP_VALUE, DETERMINANT_VALUE, CREATED_BY,
  CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATED_DATE)
VALUES ('HTH_API_PASSWORD_STATE_LOCAL_REPOSITORY_ADAPTER', 'RepositoryAdapterFactories',
 'com.ofss.digx.cz.bea.domain.hosttohost.entity.repository.adapter.LocalHthApiPasswordStateRepositoryAdapter',
 'OBDX_BU', 'ofssuser', SYSDATE, 'ofssuser', SYSDATE);

DELETE FROM DIGX_FW_CONFIG_ALL_B
 WHERE CATEGORY_ID = 'repositoryadapterconfig' AND PROP_ID = 'HTH_API_PASSWORD_OPERATION_LOCAL_REPOSITORY_ADAPTER';
INSERT INTO DIGX_FW_CONFIG_ALL_B
 (PROP_ID, CATEGORY_ID, PROP_VALUE, FACTORY_SHIPPED_FLAG, PROP_COMMENTS,
  SUMMARY_TEXT, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATED_DATE,
  OBJECT_STATUS, OBJECT_VERSION_NUMBER, EDITABLE, CATEGORY_DESCRIPTION)
VALUES ('HTH_API_PASSWORD_OPERATION_LOCAL_REPOSITORY_ADAPTER', 'repositoryadapterconfig',
