DELETE FROM DIGX_FW_CONFIG_ALL_O
 WHERE PREFERENCE_NAME = 'RepositoryAdapterFactories' AND DETERMINANT_VALUE = 'OBDX_BU' AND PROP_ID = 'HTH_API_PASSWORD_OPERATION_LOCAL_REPOSITORY_ADAPTER';
INSERT INTO DIGX_FW_CONFIG_ALL_O
 (PROP_ID, PREFERENCE_NAME, PROP_VALUE, DETERMINANT_VALUE, CREATED_BY,
