-- Oracle SQL/PLSQL; no SQL*Plus commands or substitution variables.
-- Execute each complete DECLARE/BEGIN ... END; block as one statement (no slash).
-- BCOH2H-788 / 790: DATABASE by default, UAM only when explicitly selected.
-- Run 1 Schema, 2 Process and 3 Permission first. Code key and storage settings commit together.
-- DATABASE needs no UAM URL, client ID or APIC credentials.
-- UAM requires confirmed HTTPS URL and all three paths; no guessed endpoint defaults.
-- Changing the backend does NOT migrate passwords. Stop traffic and plan credential migration first.
-- On first deployment, provide the original Code key locally; never commit a populated script.
-- On rerun, NULL reuses the configured key; a different supplied key is rejected.
-- NULL inputs retain existing settings. First deployment defaults to DATABASE / enabled.
-- Existing policy, timeouts, endpoints and APIC secret configuration are preserved.
-- Deploy the HthApiCredentialAdapterConfig node in Preferences.xml and matching Java key name.

DECLARE
  V_STORAGE_BACKEND VARCHAR2(8) := NULL;
  V_ENABLED VARCHAR2(5) := NULL;
  V_SERVICE_URL VARCHAR2(1000) := NULL;
  V_STATUS_PATH VARCHAR2(500) := NULL;
  V_SETUP_PATH VARCHAR2(500) := NULL;
  V_RESET_PATH VARCHAR2(500) := NULL;
  V_ORIGINAL_KEY VARCHAR2(4000) := NULL;
  V_EXISTING_KEY VARCHAR2(4000);
  V_KEY_BYTES RAW(2000);
  V_KEY_COUNT NUMBER;
  V_DUPLICATE_COUNT NUMBER;

  FUNCTION EXISTING_PROPERTY(P_ID VARCHAR2, P_DEFAULT VARCHAR2) RETURN VARCHAR2 IS
    V_VALUE VARCHAR2(4000);
  BEGIN
    SELECT PROP_VALUE INTO V_VALUE FROM DIGX_FW_CONFIG_ADAPTER_PROP_B
     WHERE HOST_ID = 'HthApiCredentialAdapterConfig'
       AND TRANSACTION_TYPE = 'HTH_API_PASSWORD' AND PROP_ID = P_ID;
    RETURN TRIM(V_VALUE);
  EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN P_DEFAULT;
  END;

  -- Seed defaults without changing an existing environment value.
  PROCEDURE PUT_PROPERTY(P_ID VARCHAR2, P_VALUE VARCHAR2, P_REPLACE BOOLEAN DEFAULT FALSE) IS
  BEGIN
    IF P_REPLACE THEN
      UPDATE DIGX_FW_CONFIG_ADAPTER_PROP_B
         SET PROP_VALUE = P_VALUE, LAST_UPDATED_BY = USER, LAST_UPDATED_DATE = SYSTIMESTAMP,
             OBJECT_VERSION_NUMBER = NVL(OBJECT_VERSION_NUMBER, 0) + 1
       WHERE HOST_ID = 'HthApiCredentialAdapterConfig'
         AND TRANSACTION_TYPE = 'HTH_API_PASSWORD' AND PROP_ID = P_ID;
    END IF;
    INSERT INTO DIGX_FW_CONFIG_ADAPTER_PROP_B
      (HOST_ID, TRANSACTION_TYPE, PROP_ID, PROP_VALUE, CREATED_BY, CREATION_DATE,
       LAST_UPDATED_BY, LAST_UPDATED_DATE, OBJECT_STATUS, OBJECT_VERSION_NUMBER)
    SELECT 'HthApiCredentialAdapterConfig', 'HTH_API_PASSWORD', P_ID, P_VALUE,
           USER, SYSTIMESTAMP, USER, SYSTIMESTAMP, 'A', 1 FROM DUAL
     WHERE NOT EXISTS (SELECT 1 FROM DIGX_FW_CONFIG_ADAPTER_PROP_B
                        WHERE HOST_ID = 'HthApiCredentialAdapterConfig'
                          AND TRANSACTION_TYPE = 'HTH_API_PASSWORD' AND PROP_ID = P_ID);
  END;
BEGIN
  SAVEPOINT HTH_API_PASSWORD_CONFIG;
  SELECT COUNT(*) INTO V_DUPLICATE_COUNT FROM (
    SELECT PROP_ID FROM DIGX_FW_CONFIG_ADAPTER_PROP_B
     WHERE HOST_ID = 'HthApiCredentialAdapterConfig' AND TRANSACTION_TYPE = 'HTH_API_PASSWORD'
     GROUP BY PROP_ID HAVING COUNT(*) > 1
  );
  IF V_DUPLICATE_COUNT > 0 THEN
    RAISE_APPLICATION_ERROR(-20013, 'Duplicate HTH adapter properties; resolve before deployment.');
  END IF;
  V_STORAGE_BACKEND := UPPER(COALESCE(TRIM(V_STORAGE_BACKEND),
      EXISTING_PROPERTY('STORAGE_BACKEND', 'DATABASE')));
  V_ENABLED := LOWER(COALESCE(TRIM(V_ENABLED), EXISTING_PROPERTY('ENABLED', 'true')));
  IF V_ENABLED IS NULL OR V_ENABLED NOT IN ('true', 'false') THEN
    RAISE_APPLICATION_ERROR(-20022, 'ENABLED must be true or false.');
  END IF;
  V_SERVICE_URL := COALESCE(TRIM(V_SERVICE_URL), EXISTING_PROPERTY('SERVICE_URL', NULL));
  V_STATUS_PATH := COALESCE(TRIM(V_STATUS_PATH), EXISTING_PROPERTY('STATUS_PATH', NULL));
  V_SETUP_PATH := COALESCE(TRIM(V_SETUP_PATH), EXISTING_PROPERTY('SETUP_PATH', NULL));
  V_RESET_PATH := COALESCE(TRIM(V_RESET_PATH), EXISTING_PROPERTY('RESET_PATH', NULL));
  IF V_STORAGE_BACKEND IS NULL OR V_STORAGE_BACKEND NOT IN ('DATABASE', 'UAM') THEN
    RAISE_APPLICATION_ERROR(-20021, 'STORAGE_BACKEND must be DATABASE or UAM.');
  END IF;
  IF V_STORAGE_BACKEND = 'UAM' THEN
    IF V_SERVICE_URL IS NULL OR V_SERVICE_URL NOT LIKE 'https://%'
       OR V_SERVICE_URL LIKE '%CHANGE_ME%'
       OR V_STATUS_PATH IS NULL OR V_SETUP_PATH IS NULL OR V_RESET_PATH IS NULL
       OR V_STATUS_PATH NOT LIKE '/%' OR V_SETUP_PATH NOT LIKE '/%' OR V_RESET_PATH NOT LIKE '/%' THEN
      RAISE_APPLICATION_ERROR(-20001, 'UAM requires the approved HTTPS URL and status/setup/reset paths.');
    END IF;
  END IF;
  -- Preserve the configured key so existing Code ciphertext remains decryptable.
  V_ORIGINAL_KEY := TRIM(V_ORIGINAL_KEY);
  SELECT COUNT(*) INTO V_KEY_COUNT FROM DIGX_FW_CONFIG_ADAPTER_PROP_V
   WHERE CATEGORY_ID = 'HthApiCredentialAdapterConfig'
     AND PROP_ID = 'HTH_API_PASSWORD.CODE_CIPHER_KEY';
  IF V_KEY_COUNT > 1 THEN
    RAISE_APPLICATION_ERROR(-20013, 'Duplicate Code key configuration; resolve before deployment.');
  ELSIF V_KEY_COUNT = 1 THEN
    SELECT TRIM(PROP_VALUE) INTO V_EXISTING_KEY FROM DIGX_FW_CONFIG_ADAPTER_PROP_V
     WHERE CATEGORY_ID = 'HthApiCredentialAdapterConfig'
       AND PROP_ID = 'HTH_API_PASSWORD.CODE_CIPHER_KEY';
    IF V_EXISTING_KEY IS NULL THEN
      RAISE_APPLICATION_ERROR(-20012, 'Existing Code key is empty; resolve before deployment.');
    END IF;
    IF V_ORIGINAL_KEY IS NOT NULL AND V_ORIGINAL_KEY <> V_EXISTING_KEY THEN
      RAISE_APPLICATION_ERROR(-20012, 'Existing Code key differs; refusing to overwrite.');
    END IF;
    V_ORIGINAL_KEY := V_EXISTING_KEY;
  END IF;
  IF V_ORIGINAL_KEY IS NULL
     OR NOT REGEXP_LIKE(V_ORIGINAL_KEY, '^[A-Za-z0-9+/]{43}=$', 'c') THEN
    RAISE_APPLICATION_ERROR(-20010, 'Provide the original Base64 AES-256 Code key locally.');
  END IF;
  V_KEY_BYTES := UTL_ENCODE.BASE64_DECODE(UTL_RAW.CAST_TO_RAW(V_ORIGINAL_KEY));
  IF UTL_RAW.LENGTH(V_KEY_BYTES) <> 32 THEN
    RAISE_APPLICATION_ERROR(-20011, 'The Code key must decode to 32 bytes.');
  END IF;
  IF V_KEY_COUNT = 0 THEN
    INSERT INTO DIGX_FW_CONFIG_ADAPTER_PROP_B
      (HOST_ID, TRANSACTION_TYPE, PROP_ID, PROP_VALUE, CREATED_BY, CREATION_DATE,
       LAST_UPDATED_BY, LAST_UPDATED_DATE, OBJECT_STATUS, OBJECT_VERSION_NUMBER)
    VALUES ('HthApiCredentialAdapterConfig', 'HTH_API_PASSWORD', 'CODE_CIPHER_KEY',
      V_ORIGINAL_KEY, USER, SYSTIMESTAMP, USER, SYSTIMESTAMP, 'A', 1);
  END IF;


-- The view exposes TRANSACTION_TYPE || '.' || PROP_ID; writes use only the base table.
PUT_PROPERTY('STORAGE_BACKEND', V_STORAGE_BACKEND, TRUE);
PUT_PROPERTY('ENABLED', V_ENABLED, TRUE);
PUT_PROPERTY('ADAPTER_CLASS',
    'com.ofss.digx.cz.bea.extxface.hosttohost.adapter.impl.HthApiCredentialAdapter');
IF V_STORAGE_BACKEND = 'UAM' THEN
  PUT_PROPERTY('SERVICE_URL', V_SERVICE_URL, TRUE);
  PUT_PROPERTY('STATUS_PATH', V_STATUS_PATH, TRUE);
  PUT_PROPERTY('SETUP_PATH', V_SETUP_PATH, TRUE);
  PUT_PROPERTY('RESET_PATH', V_RESET_PATH, TRUE);
END IF;
PUT_PROPERTY('CHANNEL', 'BCO');
PUT_PROPERTY('CONNECT_TIMEOUT_MS', '5000');
PUT_PROPERTY('READ_TIMEOUT_MS', '15000');
PUT_PROPERTY('POLICY_MIN_LENGTH', '8');
PUT_PROPERTY('POLICY_MAX_LENGTH', '16');
PUT_PROPERTY('POLICY_NUMERIC_REQUIRED', '2');
PUT_PROPERTY('POLICY_ALPHABET_REQUIRED', '1');
PUT_PROPERTY('POLICY_SPECIAL_ALLOWED', 'false');
PUT_PROPERTY('POLICY_SPACES_ALLOWED', 'false');

-- Repository factories resolve the same local implementation for base and OBDX_BU settings.
DELETE FROM DIGX_FW_CONFIG_ALL_B
 WHERE CATEGORY_ID = 'repositoryadapterconfig' AND PROP_ID = 'HTH_API_PASSWORD_CREDENTIAL_LOCAL_REPOSITORY_ADAPTER';
INSERT INTO DIGX_FW_CONFIG_ALL_B
 (PROP_ID, CATEGORY_ID, PROP_VALUE, FACTORY_SHIPPED_FLAG, PROP_COMMENTS,
  SUMMARY_TEXT, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATED_DATE,
  OBJECT_STATUS, OBJECT_VERSION_NUMBER, EDITABLE, CATEGORY_DESCRIPTION)
VALUES ('HTH_API_PASSWORD_CREDENTIAL_LOCAL_REPOSITORY_ADAPTER', 'repositoryadapterconfig',
