SELECT N.ID, N.APPROVAL_REF, N.CHANGE_TYPE, N.RECIPIENT_ROLE, N.CHANNEL, N.STATE,
 N.PARENT_ID, N.COD_ACT_DATA_ID, M.REFNUMBER, M.EVENTID, M.RESPONSE_STATUS, N.UPDATED_AT
FROM DIGX_CZ_HTH_ACCESS_NOTIFY N LEFT JOIN DIGX_CZ_EMAIL_MNG M ON M.REFNUMBER='HA'||N.ID
WHERE N.UPDATED_AT >= CURRENT_TIMESTAMP - INTERVAL '7' DAY ORDER BY N.UPDATED_AT DESC;

