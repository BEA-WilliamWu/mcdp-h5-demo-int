FROM DIGX_CZ_HTH_CONTACT_OUTBOX GROUP BY EVENT_ID, CHANNEL, STATE ORDER BY EVENT_ID, CHANNEL, STATE;
SELECT N.ID, N.APPROVAL_REF, N.RECIPIENT_ROLE, N.EVENT_ID, N.STATE,
       N.FALLBACK_ID, M.REFNUMBER, M.RESPONSE_STATUS, M.LAST_UPDATED_DATE
