-- Accept equivalent valid indexes, as script 1 does. Names below are used on new installs.
WITH expected_indexes AS (
  SELECT 'UX_HTH_CRM_DEDUP' index_name, 'DEDUP_KEY' column_names, 'UNIQUE' index_uniqueness FROM DUAL
  UNION ALL SELECT 'IX_HTH_CRM_DATE_ACT','EVENT_DTE,ACTIVITY_KEY','NONUNIQUE' FROM DUAL
  UNION ALL SELECT 'IX_HTH_CRM_SOURCE','SOURCE_TRX_REF_NBR','NONUNIQUE' FROM DUAL
), actual_indexes AS (
  SELECT i.INDEX_NAME, i.TABLE_OWNER, i.TABLE_NAME, i.UNIQUENESS, i.STATUS, i.INDEX_TYPE,
         (SELECT LISTAGG(c.COLUMN_NAME,',') WITHIN GROUP (ORDER BY c.COLUMN_POSITION)
          FROM ALL_IND_COLUMNS c WHERE c.INDEX_OWNER=i.OWNER AND c.INDEX_NAME=i.INDEX_NAME) AS column_names
  FROM ALL_INDEXES i WHERE i.OWNER='HTH_BEA'
    AND ((i.TABLE_OWNER='HTH_BEA' AND i.TABLE_NAME='HTH_CRM_EVENT_DETAILS')
         OR i.INDEX_NAME IN (SELECT index_name FROM expected_indexes))
)
SELECT s.index_name AS DEFAULT_INDEX_NAME, s.column_names AS EXPECTED_COLUMNS,
       CASE WHEN EXISTS (SELECT 1 FROM ALL_OBJECTS o WHERE o.OWNER='HTH_BEA'
                         AND o.OBJECT_NAME=s.index_name AND o.OBJECT_TYPE<>'INDEX')
              THEN 'FAIL: reserved index name belongs to another object'
            WHEN EXISTS (SELECT 1 FROM actual_indexes bad
                         WHERE (bad.INDEX_NAME=s.index_name
                           OR (bad.TABLE_OWNER='HTH_BEA' AND bad.TABLE_NAME='HTH_CRM_EVENT_DETAILS'
                               AND bad.column_names=s.column_names))
                           AND (bad.TABLE_OWNER<>'HTH_BEA' OR bad.TABLE_NAME<>'HTH_CRM_EVENT_DETAILS'
                             OR NVL(bad.column_names,'?')<>s.column_names OR bad.UNIQUENESS<>s.index_uniqueness
                             OR NVL(bad.STATUS,'?')<>'VALID' OR bad.INDEX_TYPE<>'NORMAL'))
              THEN 'FAIL: conflicting index definition'
            WHEN COUNT(i.INDEX_NAME)>0 THEN 'PASS'
            ELSE 'FAIL: valid index missing or incompatible' END AS INDEX_CHECK,
       LISTAGG(i.INDEX_NAME,',') WITHIN GROUP (ORDER BY i.INDEX_NAME) AS MATCHING_INDEXES
FROM expected_indexes s LEFT JOIN actual_indexes i
  ON i.TABLE_OWNER='HTH_BEA' AND i.TABLE_NAME='HTH_CRM_EVENT_DETAILS'
     AND i.column_names=s.column_names AND i.UNIQUENESS=s.index_uniqueness
     AND i.STATUS='VALID' AND i.INDEX_TYPE='NORMAL'
GROUP BY s.index_name,s.column_names,s.index_uniqueness ORDER BY s.index_name;

