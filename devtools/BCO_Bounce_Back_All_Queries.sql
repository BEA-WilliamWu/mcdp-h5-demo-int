WITH p AS (
 SELECT DATE '2026-10-16' AS from_time,
        DATE '2026-10-24' AS to_time FROM DUAL
), imported AS (
 SELECT 'CCB_EMAIL' file_type, BATCH_FILE_NAME, RECORD_LAST_UPDATED FROM DIGX_CZ_BATCH_BOUNCE_BACK_CCBEMAIL
 UNION ALL SELECT 'CCB_SMS', BATCH_FILE_NAME, RECORD_LAST_UPDATED FROM DIGX_CZ_BATCH_BOUNCE_BACK_CCBSMS
