-- 使用数据库记录的时间；先看下面时区。区间含起点、不含终点。
-- 不按邮箱/手机号/Event ID过滤，避免漏掉旧地址、公司、审批人及意外触发的事件。
-- 数据可能包含同时间其他业务，请同时提供测试目标用户/公司及人员角色对应，以便准确归属。
SELECT SYS_CONTEXT('USERENV','DB_NAME') DB_NAME,
 SYS_CONTEXT('USERENV','CURRENT_SCHEMA') CURRENT_SCHEMA,
 SYSDATE DB_DATE, SYSTIMESTAMP DB_TIMESTAMP, DBTIMEZONE, SESSIONTIMEZONE
FROM DUAL;

SELECT REFNUMBER, ORG_REF_NO, COD_ACT_DATA_ID, EVENTID, ACTIVITYID,
 RECIPIENTID, CUSTOMERID, PARTYID, ALERT_TYPE, RESPONSE_STATUS,
 SUBJECT, LAST_UPDATED_DATE
FROM DIGX_CZ_EMAIL_MNG
WHERE LAST_UPDATED_DATE >= TO_TIMESTAMP(:from_time, 'YYYY-MM-DD HH24:MI:SS')
 AND LAST_UPDATED_DATE < TO_TIMESTAMP(:to_time, 'YYYY-MM-DD HH24:MI:SS')
ORDER BY LAST_UPDATED_DATE DESC, REFNUMBER DESC;

