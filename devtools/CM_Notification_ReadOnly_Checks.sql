-- Q5 时间范围内所有通知，倒序。把两个时间改成实际操作/审批前后5分钟。
-- 先不限制Event/Recipient，避免漏公司、AP、旧地址、意外PIN通知。
-- 时间按数据库存储时间解释；先用下一句记录数据库时区/时间作参照。
SELECT SYSDATE DB_DATE, SYSTIMESTAMP DB_TIMESTAMP, DBTIMEZONE, SESSIONTIMEZONE FROM DUAL;
SELECT REFNUMBER, ORG_REF_NO, COD_ACT_DATA_ID, EVENTID, ACTIVITYID,
       RECIPIENTID, CUSTOMERID, PARTYID, ALERT_TYPE,
       RESPONSE_STATUS, SUBJECT, LAST_UPDATED_DATE
FROM DIGX_CZ_EMAIL_MNG
WHERE LAST_UPDATED_DATE >= TO_TIMESTAMP('2026-10-15 18:00:00','YYYY-MM-DD HH24:MI:SS')
  AND LAST_UPDATED_DATE <  TO_TIMESTAMP('2026-10-15 18:10:00','YYYY-MM-DD HH24:MI:SS')
ORDER BY LAST_UPDATED_DATE DESC, REFNUMBER DESC;

-- Q6 同一时间范围按事件/渠道/收件地址统计。不同event不合并为“重复”。
-- 多于一条也可能是重试或重复测试，需用REFNUMBER/操作时间进一步核对。
SELECT EVENTID, ALERT_TYPE, RECIPIENTID, RESPONSE_STATUS,
       COUNT(*) RECORD_COUNT, COUNT(DISTINCT REFNUMBER) REF_COUNT,
       MIN(LAST_UPDATED_DATE) FIRST_AT, MAX(LAST_UPDATED_DATE) LAST_AT
FROM DIGX_CZ_EMAIL_MNG
WHERE LAST_UPDATED_DATE >= TO_TIMESTAMP('2026-10-15 18:00:00','YYYY-MM-DD HH24:MI:SS')
  AND LAST_UPDATED_DATE <  TO_TIMESTAMP('2026-10-15 18:10:00','YYYY-MM-DD HH24:MI:SS')
GROUP BY EVENTID, ALERT_TYPE, RECIPIENTID, RESPONSE_STATUS
ORDER BY LAST_AT DESC, EVENTID, ALERT_TYPE, RECIPIENTID;

