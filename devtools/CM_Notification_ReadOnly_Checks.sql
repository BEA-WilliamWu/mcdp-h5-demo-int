-- Q1 路由及状态。保留全部映射，勿 MAX/ROWNUM=1 随便选一个。
SELECT r.COD_ACT_ID, r.COD_EVENT_ID, r.COD_ACTION_ID,
       r.TXT_DEST_TYP, r.LOCALE, r.SUBSCRIBER_TYPE, r.SUBSCRIBER_VALUE,
       r.RECIPIENT_TYPE, r.FLG_CONDITIONAL, r.COD_MSG_TMPL_ID,
       t.DETERMINANT_VALUE, t.OBJECT_STATUS AS TEMPLATE_STATUS,
       t.DESTINATION_TYPE AS TEMPLATE_CHANNEL
FROM DIGX_EP_EVT_REC_B r
LEFT JOIN DIGX_EP_MSG_TMPL_B t
  ON t.COD_TMPL_ID = r.COD_MSG_TMPL_ID
 AND t.DETERMINANT_VALUE = 'OBDX_BU'
WHERE r.COD_EVENT_ID IN (
    'USER_MANAGEMENT_CREATE',
    'USER_MANAGEMENT_EDIT',
    'USER_ACCOUNT_ACCESS_UPDATE',
    'HTH_USER_ACCOUNT_ACCESS_UPDATE',
    'HTH_USER_ACCOUNT_ACCESS_COMPANY',
    'HTH_API_PASSWORD_CODE_APPROVED_USER_EMAIL_EVENT',
    'HTH_API_PASSWORD_CODE_APPROVED_COMPANY_EMAIL_EVENT',
    'HTH_API_PASSWORD_SETUP_SUCCESS',
    'HTH_API_PASSWORD_RESET_SUCCESS',
    'INFO_UPDATE_BY_CORP_ADMIN',
    'USER_EMAIL_ADDRESS_UPDATE',
    'USER_MOBILE_NUMBER_UPDATED_REMINDER',
    'CORPORATEPLUS_WELCOME_MAIL')
ORDER BY r.COD_EVENT_ID, r.COD_ACT_ID, r.TXT_DEST_TYP,
         r.SUBSCRIBER_TYPE, r.SUBSCRIBER_VALUE, r.LOCALE, r.COD_MSG_TMPL_ID;

