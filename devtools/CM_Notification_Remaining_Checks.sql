SELECT PROP_ID, PREFERENCE_NAME, PROP_VALUE, DETERMINANT_VALUE,
       LAST_UPDATED_DATE
FROM DIGX_CZ_FW_CONFIG_ALL_O
WHERE PROP_ID IN ('EMAIL_DISPATCHER_SKIP_PARTY_EMAIL_LIST',
                  'EMAIL_DISPATCHER_SKIP_CUST_EMAIL_LIST')
ORDER BY PROP_ID, PREFERENCE_NAME, DETERMINANT_VALUE;

-- Q11：实际邮件和短信处理历史。此次请导出下面查询的结果，
-- 不要导出SYSDATE/Schema那条环境信息查询。
-- from_time/to_time格式：YYYY-MM-DD HH24:MI:SS；使用该测试的审批/执行时间窗口。
-- BCO和HTH各场景分别导出，文件名标明场景。不要按收件人或事件过滤，避免遗漏公司/旧地址/AP。
-- 此表处理状态不等于最终送达；失败原因必要时结合同时段后台日志。
SELECT REFNUMBER, ORG_REF_NO, COD_ACT_DATA_ID, EVENTID, ACTIVITYID,
       RECIPIENTID, CUSTOMERID, PARTYID, ALERT_TYPE,
       RESPONSE_STATUS, SUBJECT, LAST_UPDATED_DATE
FROM DIGX_CZ_EMAIL_MNG
WHERE LAST_UPDATED_DATE >= TO_TIMESTAMP(:from_time, 'YYYY-MM-DD HH24:MI:SS')
  AND LAST_UPDATED_DATE < TO_TIMESTAMP(:to_time, 'YYYY-MM-DD HH24:MI:SS')
ORDER BY LAST_UPDATED_DATE DESC, REFNUMBER DESC;
