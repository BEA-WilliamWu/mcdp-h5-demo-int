-- Production FIRST_DEPLOY already contains this column; do not run both scripts there.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET VERIFY OFF
ALTER TABLE HTH_BEA.HTH_API_PASSWORD_CODE ADD (REMOTE_CLIENT_ID VARCHAR2(64 BYTE));
-- Preserve the old DSP-client binding on historical Code reservations before removing the old table.
UPDATE HTH_BEA.HTH_API_PASSWORD_CODE C
SET REMOTE_CLIENT_ID = (SELECT O.REMOTE_CLIENT_ID FROM HTH_BEA.HTH_API_PASSWORD_OPERATION O
                       WHERE O.REQUEST_ID = C.REQUEST_ID AND O.CODE_ID = C.ID AND O.STORAGE_BACKEND = 'DSP')
WHERE EXISTS (SELECT 1 FROM HTH_BEA.HTH_API_PASSWORD_OPERATION O
              WHERE O.REQUEST_ID = C.REQUEST_ID AND O.CODE_ID = C.ID AND O.STORAGE_BACKEND = 'DSP');
COMMIT;
-- Configure the internal APIC subscription for both endpoints. No values are embedded in source.
SET DEFINE ON
ACCEPT DSP_PUBLIC_KEY_URL CHAR PROMPT 'Internal APIC DSP public-key URL: '
ACCEPT DSP_MODIFICATION_URL CHAR PROMPT 'Internal APIC DSP modification URL: '
ACCEPT DSP_PASSWORD_CLIENT_ID CHAR PROMPT 'Internal APIC subscription ID: ' HIDE
ACCEPT DSP_PASSWORD_CLIENT_SECRET CHAR PROMPT 'Internal APIC subscription secret: ' HIDE
MERGE INTO DIGX_FW_CONFIG_ADAPTER_PROP_B T
USING (SELECT 'HthApiCredentialAdapterConfig' HOST_ID, 'HTH_API_PASSWORD' TRANSACTION_TYPE,
       'DSP_PUBLIC_KEY_URL' PROP_ID, '&&DSP_PUBLIC_KEY_URL' PROP_VALUE FROM DUAL) S
ON (T.HOST_ID=S.HOST_ID AND T.TRANSACTION_TYPE=S.TRANSACTION_TYPE AND T.PROP_ID=S.PROP_ID)
WHEN MATCHED THEN UPDATE SET T.PROP_VALUE=S.PROP_VALUE, T.LAST_UPDATED_BY=USER, T.LAST_UPDATED_DATE=SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
 (HOST_ID,TRANSACTION_TYPE,PROP_ID,PROP_VALUE,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATED_DATE,OBJECT_STATUS,OBJECT_VERSION_NUMBER)
 VALUES (S.HOST_ID,S.TRANSACTION_TYPE,S.PROP_ID,S.PROP_VALUE,USER,SYSTIMESTAMP,USER,SYSTIMESTAMP,'A',1);
MERGE INTO DIGX_FW_CONFIG_ADAPTER_PROP_B T
USING (SELECT 'HthApiCredentialAdapterConfig' HOST_ID, 'HTH_API_PASSWORD' TRANSACTION_TYPE,
       'DSP_MODIFICATION_URL' PROP_ID, '&&DSP_MODIFICATION_URL' PROP_VALUE FROM DUAL) S
ON (T.HOST_ID=S.HOST_ID AND T.TRANSACTION_TYPE=S.TRANSACTION_TYPE AND T.PROP_ID=S.PROP_ID)
WHEN MATCHED THEN UPDATE SET T.PROP_VALUE=S.PROP_VALUE, T.LAST_UPDATED_BY=USER, T.LAST_UPDATED_DATE=SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
 (HOST_ID,TRANSACTION_TYPE,PROP_ID,PROP_VALUE,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATED_DATE,OBJECT_STATUS,OBJECT_VERSION_NUMBER)
 VALUES (S.HOST_ID,S.TRANSACTION_TYPE,S.PROP_ID,S.PROP_VALUE,USER,SYSTIMESTAMP,USER,SYSTIMESTAMP,'A',1);
MERGE INTO DIGX_FW_CONFIG_ADAPTER_PROP_B T
USING (SELECT 'HthApiCredentialAdapterConfig' HOST_ID, 'HTH_API_PASSWORD' TRANSACTION_TYPE,
       'DSP_APIC_CLIENT_ID' PROP_ID, '&&DSP_PASSWORD_CLIENT_ID' PROP_VALUE FROM DUAL) S
ON (T.HOST_ID=S.HOST_ID AND T.TRANSACTION_TYPE=S.TRANSACTION_TYPE AND T.PROP_ID=S.PROP_ID)
WHEN MATCHED THEN UPDATE SET T.PROP_VALUE=S.PROP_VALUE, T.LAST_UPDATED_BY=USER, T.LAST_UPDATED_DATE=SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
 (HOST_ID,TRANSACTION_TYPE,PROP_ID,PROP_VALUE,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATED_DATE,OBJECT_STATUS,OBJECT_VERSION_NUMBER)
 VALUES (S.HOST_ID,S.TRANSACTION_TYPE,S.PROP_ID,S.PROP_VALUE,USER,SYSTIMESTAMP,USER,SYSTIMESTAMP,'A',1);
MERGE INTO DIGX_FW_CONFIG_ADAPTER_PROP_B T
USING (SELECT 'HthApiCredentialAdapterConfig' HOST_ID, 'HTH_API_PASSWORD' TRANSACTION_TYPE,
       'DSP_APIC_CLIENT_SECRET' PROP_ID, '&&DSP_PASSWORD_CLIENT_SECRET' PROP_VALUE FROM DUAL) S
ON (T.HOST_ID=S.HOST_ID AND T.TRANSACTION_TYPE=S.TRANSACTION_TYPE AND T.PROP_ID=S.PROP_ID)
WHEN MATCHED THEN UPDATE SET T.PROP_VALUE=S.PROP_VALUE, T.LAST_UPDATED_BY=USER, T.LAST_UPDATED_DATE=SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
 (HOST_ID,TRANSACTION_TYPE,PROP_ID,PROP_VALUE,CREATED_BY,CREATION_DATE,LAST_UPDATED_BY,LAST_UPDATED_DATE,OBJECT_STATUS,OBJECT_VERSION_NUMBER)
 VALUES (S.HOST_ID,S.TRANSACTION_TYPE,S.PROP_ID,S.PROP_VALUE,USER,SYSTIMESTAMP,USER,SYSTIMESTAMP,'A',1);
COMMIT;
